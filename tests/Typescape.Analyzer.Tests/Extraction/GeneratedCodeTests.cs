using Microsoft.CodeAnalysis;

namespace Typescape.Analyzer.Tests.Extraction;

public class GeneratedCodeTests
{
    [Fact]
    public void A_document_a_source_generator_produced_is_generated_by_the_generator_whatever_its_name()
    {
        var compilation = RuleTest.Compile(
        [
            ("App/obj/Generators/Order.Json.g.cs", "class OrderJson { }"),
            ("App/obj/Generators/Registrations.cs", "class Registrations { }"),
            ("App/Order.cs", "class Order { }"),
        ]);
        var context = RuleTest.Context with
        {
            GeneratedDocumentPaths = new HashSet<string>
            {
                RuleTest.FullPath("App/obj/Generators/Order.Json.g.cs"),
                RuleTest.FullPath("App/obj/Generators/Registrations.cs"),
            },
        };

        RuleTest.Match(RuleTest.Keep(RuleTest.Extract(compilation, context), documents: true));
    }

    [Fact]
    public void A_document_is_generated_by_convention_from_its_file_name()
    {
        var facts = RuleTest.Extract(
        [
            ("App/Order.g.cs", "class A { }"),
            ("App/Order.g.i.cs", "class B { }"),
            ("App/Order.generated.cs", "class C { }"),
            ("App/Form.Designer.cs", "class D { }"),
            ("App/obj/TemporaryGeneratedFile_E7A71F73.cs", "class E { }"),
            ("App/g.cs", "class F { }"),
            ("App/Designer.cs", "class G { }"),
            ("App/Order.gen.cs", "class H { }"),
        ]);

        RuleTest.Match(RuleTest.Keep(facts, documents: true));
    }

    [Fact]
    public void A_document_is_generated_by_convention_from_an_auto_generated_comment_before_its_first_token()
    {
        var facts = RuleTest.Extract(
        [
            ("App/Header.cs", """
                // ------------------------------------------------------------------------------
                // <auto-generated>
                //     This code was generated by a tool.
                // </auto-generated>
                // ------------------------------------------------------------------------------
                class A { }
                """),
            ("App/Old.cs", "/* <autogenerated /> */ class B { }"),
            ("App/AfterUsings.cs", """
                #nullable enable
                using System;

                // <auto-generated/>
                class C { }
                """),
            ("App/Capitalized.cs", """
                // <Auto-Generated/>
                class D { }
                """),
        ]);

        RuleTest.Match(RuleTest.Keep(facts, documents: true));
    }

    [Fact]
    public void An_analyzer_config_generated_code_setting_overrides_the_convention_but_not_a_source_generator()
    {
        var compilation = RuleTest.Compile(
        [
            ("App/Marked.cs", "class A { }"),
            ("App/Unmarked.g.cs", "class B { }"),
            ("App/obj/Generators/Unmarked.cs", "class C { }"),
        ]);
        var settings = new Dictionary<string, GeneratedKind>
        {
            [RuleTest.FullPath("App/Marked.cs")] = GeneratedKind.MarkedGenerated,
            [RuleTest.FullPath("App/Unmarked.g.cs")] = GeneratedKind.NotGenerated,
            [RuleTest.FullPath("App/obj/Generators/Unmarked.cs")] = GeneratedKind.NotGenerated,
        };
        var provider = new GeneratedCodeSettings(tree => settings.GetValueOrDefault(tree.FilePath, GeneratedKind.Unknown));
        var context = RuleTest.Context with
        {
            GeneratedDocumentPaths = new HashSet<string> { RuleTest.FullPath("App/obj/Generators/Unmarked.cs") },
        };

        var facts = RuleTest.Extract(compilation.WithOptions(compilation.Options.WithSyntaxTreeOptionsProvider(provider)), context);

        RuleTest.Match(RuleTest.Keep(facts, documents: true));
    }

    [Fact]
    public void A_half_generated_partial_type_flags_each_declaration_and_member_on_its_own()
    {
        var facts = RuleTest.Extract(
        [
            ("App/Order.cs", """
                partial class Order
                {
                    public int Total() => 0;
                }
                """),
            ("App/Order.Json.cs", """
                using System.CodeDom.Compiler;

                [GeneratedCode("JsonGen", "1.0")]
                partial class Order
                {
                    public string ToJson() => "";
                }
                """),
            ("App/Order.Designer.cs", """
                partial class Order
                {
                    void InitializeComponent() { }
                }
                """),
        ]);

        RuleTest.Match(RuleTest.Keep(facts, types: true, members: true));
    }

    [Fact]
    public void A_member_is_generated_when_it_or_its_property_carries_a_generated_attribute()
    {
        var facts = RuleTest.Extract("""
            using System;
            using System.CodeDom.Compiler;
            using System.Runtime.CompilerServices;

            class Order
            {
                int total;

                [CompilerGenerated]
                public Order() { }

                [GeneratedCode("tool", "1.0")]
                public int Total() => total;

                public int Manual() => total;

                [GeneratedCode("tool", "1.0")]
                public int Lines
                {
                    get => total;
                    set => total = value;
                }

                public int Count
                {
                    [CompilerGenerated]
                    get => total;
                    set => total = value;
                }

                [GeneratedCode("tool", "1.0")]
                public event EventHandler Changed
                {
                    add { }
                    remove { }
                }
            }
            """);

        RuleTest.Match(RuleTest.Keep(facts, types: true, members: true));
    }

    [Fact]
    public void A_nested_type_in_a_generated_declaration_is_generated_and_its_attribute_does_not_reach_its_containing_type()
    {
        var facts = RuleTest.Extract("""
            using System.CodeDom.Compiler;

            [GeneratedCode("tool", "1.0")]
            class Settings
            {
                class Section
                {
                    void Load() { }
                }
            }

            class Order
            {
                [GeneratedCode("tool", "1.0")]
                class Line
                {
                    void Validate() { }
                }

                void Ship() { }
            }
            """);

        RuleTest.Match(RuleTest.Keep(facts, types: true, members: true));
    }

    [Fact]
    public void Top_level_statements_in_a_generated_document_are_a_generated_declaration_and_entry_point()
    {
        var compilation = RuleTest.Compile([("App/Program.g.cs", "System.Console.WriteLine();")], OutputKind.ConsoleApplication);

        RuleTest.Match(RuleTest.Keep(RuleTest.Extract(compilation), documents: true, types: true, members: true));
    }

    [Fact]
    public void A_polyfilled_generated_attribute_counts_as_the_real_one()
    {
        var facts = RuleTest.Extract("""
            namespace System.Runtime.CompilerServices
            {
                [System.AttributeUsage(System.AttributeTargets.All)]
                sealed class CompilerGeneratedAttribute : System.Attribute { }
            }

            class Order
            {
                [System.Runtime.CompilerServices.CompilerGenerated]
                void Validate() { }
            }
            """);

        RuleTest.Match(RuleTest.Keep(facts, members: true));
    }
}
