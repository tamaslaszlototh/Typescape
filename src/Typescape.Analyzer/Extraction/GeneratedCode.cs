using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Typescape.Snapshot.Records;

namespace Typescape.Analyzer.Extraction;

/// <summary>
/// Which documents, declarations and Executable Members of one project are generated code. One per extraction unit:
/// its cache is not thread-safe.
/// </summary>
internal sealed class GeneratedCode(Compilation compilation, ProjectContext context, CancellationToken cancellationToken)
{
    private static readonly string[] ConventionalSuffixes = [".designer", ".generated", ".g", ".g.i"];

    private static readonly string[] HeaderMarkers = ["<autogenerated", "<auto-generated"];

    private readonly Dictionary<SyntaxTree, GeneratedReason?> reasons = [];

    /// <summary>
    /// The <see cref="DocumentFact.GeneratedReason"/> of <paramref name="document"/>: <see cref="GeneratedReason.Generator"/>
    /// when a source generator produced it, else <see cref="GeneratedReason.Convention"/> when a <c>generated_code</c>
    /// analyzer-config setting, or without one its file name or <c>&lt;auto-generated&gt;</c> header, says so.
    /// </summary>
    public GeneratedReason? Reason(SyntaxTree document)
    {
        if (!reasons.TryGetValue(document, out var reason))
        {
            reason = Decide(document);
            reasons[document] = reason;
        }

        return reason;
    }

    /// <summary>The <see cref="TypeDeclarationFact.Generated"/> flag of one of <paramref name="type"/>'s declarations.</summary>
    public bool DeclarationIsGenerated(INamedTypeSymbol type, SyntaxReference declaration) =>
        Reason(declaration.SyntaxTree) is not null
        || type.GetAttributes().Any(attribute => Marks(attribute) && Encloses(declaration, attribute.ApplicationSyntaxReference))
        || type.ContainingType is { } containing
            && containing.DeclaringSyntaxReferences.Any(outer => Encloses(outer, declaration) && DeclarationIsGenerated(containing, outer));

    /// <summary>The <see cref="ExecutableMemberFact.Generated"/> flag of <paramref name="member"/>.</summary>
    /// <param name="type">The own type the member belongs to: for an extension-block member, the static class.</param>
    /// <param name="body">The member's syntax that holds its body.</param>
    public bool MemberIsGenerated(INamedTypeSymbol type, IMethodSymbol member, SyntaxNode body) =>
        type.DeclaringSyntaxReferences.Any(declaration => Encloses(declaration, body.GetReference()) && DeclarationIsGenerated(type, declaration))
        || member.GetAttributes().Any(Marks)
        || member.AssociatedSymbol?.GetAttributes().Any(Marks) == true;

    private GeneratedReason? Decide(SyntaxTree document)
    {
        if (context.GeneratedDocumentPaths.Contains(document.FilePath))
        {
            return GeneratedReason.Generator;
        }

        var conventional = compilation.Options.SyntaxTreeOptionsProvider?.IsGenerated(document, cancellationToken) switch
        {
            GeneratedKind.MarkedGenerated => true,
            GeneratedKind.NotGenerated => false,
            _ => ConventionalFileName(document.FilePath) || ConventionalHeader(document),
        };
        return conventional ? GeneratedReason.Convention : null;
    }

    // Matched by name, so a polyfilled copy of either attribute counts too.
    private static bool Marks(AttributeData attribute) =>
        attribute.AttributeClass is { Name: "GeneratedCodeAttribute" or "CompilerGeneratedAttribute" } type
        && type.ToDisplayString() is "System.CodeDom.Compiler.GeneratedCodeAttribute" or "System.Runtime.CompilerServices.CompilerGeneratedAttribute";

    private static bool Encloses(SyntaxReference outer, SyntaxReference? inner) =>
        inner is not null && inner.SyntaxTree == outer.SyntaxTree && outer.Span.Contains(inner.Span);

    // As Roslyn's GeneratedCodeUtilities decides it for analyzers.
    private static bool ConventionalFileName(string path)
    {
        var name = Path.GetFileName(path);
        return name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase)
            || (Path.GetExtension(name).Length > 0
                && ConventionalSuffixes.Any(suffix => Path.GetFileNameWithoutExtension(name).EndsWith(suffix, StringComparison.OrdinalIgnoreCase)));
    }

    private bool ConventionalHeader(SyntaxTree document) =>
        document.GetRoot(cancellationToken).GetLeadingTrivia()
            .Where(trivia => trivia.Kind() is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia
                or SyntaxKind.SingleLineDocumentationCommentTrivia or SyntaxKind.MultiLineDocumentationCommentTrivia)
            .Any(comment => HeaderMarkers.Any(marker => comment.ToString().Contains(marker, StringComparison.Ordinal)));
}
